    public static void GenerateCatalog(List<GameObject> items, string catalogPath) {
        HandItemCatalog catalog =
            AssetDatabase.LoadAssetAtPath<HandItemCatalog>(
                catalogPath
            );
        if (catalog == null) {
            string directory =
                Path.GetDirectoryName(catalogPath);
            if (!Directory.Exists(directory))
                Directory.CreateDirectory(directory);
            catalog = ScriptableObject.CreateInstance<HandItemCatalog>();
            AssetDatabase.CreateAsset(
                catalog,
                catalogPath
            );
        }
        catalog.SetItems(items);
        EditorUtility.SetDirty(catalog);
    }

    public static void GenerateEnum(List<GameObject> items, string enumName, string enumPath) {
        string directory = Path.GetDirectoryName(enumPath);
        // TODO: Maybe just log error and return if dir doesn't exist?
        if (!Directory.Exists(directory))
            Directory.CreateDirectory(directory);
        StringBuilder sb = new();
        sb.AppendLine($"// AUTO-GENERATED BY {nameof(HandItemGenerator)}. DO NOT EDIT!!!");
        sb.AppendLine();
        // TODO: Byte might not be enough for this. Consider changing.
        sb.AppendLine($"public enum {enumName} : byte {{");
        for (int i = 0; i < items.Count; i++) {
            sb.Append("    ");
            sb.Append(items[i].name);
            sb.Append(" = ");
            sb.Append(i);
            sb.AppendLine(",");
        }
        sb.AppendLine("}");
        File.WriteAllText(enumPath, sb.ToString());
    }

