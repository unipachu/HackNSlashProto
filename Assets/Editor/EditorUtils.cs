    public static bool IsValidIdentifier(string id) {
        if (string.IsNullOrEmpty(id))
            return false;
        if (!char.IsLetter(id[0]) && id[0] != '_')
            return false;
        for (int i = 1; i < id.Length; i++) {
            if (!char.IsLetterOrDigit(id[i]) && id[i] != '_')
                return false;
        }
        if (IsCSharpKeyword(id))
            return false;
        return true;
    }

    public static bool Validate(List<GameObject> items) {
        HashSet<string> ids = new();
        foreach (GameObject item in items) {
            if (string.IsNullOrWhiteSpace(item.name)) {
                Debug.LogError($"Hand item '{item.name}' has an empty ID.", item);
                return false;
            }
            if (!IsValidIdentifier(item.name)) {
                Debug.LogError(
                    $"Hand item '{item.name}' has invalid ID '{item.name}'. IDs must be valid C# identifiers.",
                    item
                );
                return false;
            }
            if (!ids.Add(item.name)) {
                Debug.LogError($"Duplicate HandItem ID: '{item.name}'.");
                return false;
            }
        }
        return true;
    }
